using System.Security;
using System.Text;
using System.Text.RegularExpressions;

namespace Tallow.ManagedBuild.Export;

/// <summary>
/// NativeAOT export of a C# game. Tallow's managed runtime, Tallow.API and the game's assemblies (already compiled
/// into build/csharp/&lt;config&gt;) are compiled ahead of time into ONE native library: Managed/Native/libTallowGame.so
/// on Linux, Managed/Native/TallowGame.dll on Windows, Managed/Native/libTallowGame.dylib on macOS. The precompiled
/// player loads it instead of starting .NET. The package then holds no .NET runtime, no IL assemblies and no game
/// source; native symbols go to a private folder beside the build.
///
/// Where each is built (<see cref="CanBuild"/>): a Linux library on any machine with Zig installed (Zig.cs), or on
/// Linux with the system's clang or gcc; a Windows library on Windows, or on Linux with lld-link and the Windows SDK
/// and CRT that tools/windows/setup.sh downloads (xwin, in TALLOW_WIN); a macOS library on a Mac with Apple's
/// command line tools (xcode-select --install), for the chip the engine's macOS player is built for.
/// </summary>
internal static class NativeAot
{
    // Trim/AOT analysis warnings that point at real problems in a NativeAOT game.
    static readonly Regex Analysis = new(@"warning (IL[23]\d{3}):\s*(.*?)(?: \[[^\]]*\])?$", RegexOptions.CultureInvariant);
    static readonly string[] Framework = { "System.", "Microsoft.", "Internal.", "Interop.", "ILCompiler." };

    const string GameHelp = """
        These are in the game's own code and can break it in a NativeAOT build (code made at run time, or
        members trimming removes). Change the code (avoid MakeGenericType/MakeGenericMethod, Activator on types found by name,
        Type.GetType of strings), or, if you have checked it works when exported as NativeAOT, keep it with
          [System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage("AOT", "<code>", Justification = "<why it is safe>")]
        on the method. Or export with the JIT runtime (Build window: JIT; --csharp-runtime jit).
        """;

    const string Exports = """
        // Generated by Tallow.Build export: the one export of a NativeAOT game library.
        using System.Runtime.CompilerServices;
        using System.Runtime.InteropServices;

        public static unsafe class TallowNativeExports
        {
            [UnmanagedCallersOnly(EntryPoint = "tallow_native_register", CallConvs = [typeof(CallConvCdecl)])]
            public static int Register(delegate* unmanaged[Cdecl]<byte*, nint, int> register, int hostAbi, byte* error, int errorCapacity) =>
                global::Tallow.ManagedRuntime.NativeHost.Register(register, hostAbi,
                    new global::Tallow.Generated.TallowGeneratedGameRegistry(), error, errorCapacity);
        }

        """;

    public static string LibraryName(Target target) =>
        target switch { Target.Windows => "TallowGame.dll", Target.MacOS => "libTallowGame.dylib", _ => "libTallowGame.so" };

    /// <summary>Whether this machine can make a NativeAOT library for the target at all.</summary>
    public static bool CanBuild(Target target) => target switch
    {
        Target.Linux => ExportUtil.HostLinux || Zig.Find() != null,
        Target.Windows => ExportUtil.HostWindows || ExportUtil.HostLinux,
        Target.MacOS => ExportUtil.HostMac && AppleToolsInstalled(),
        // Android Studio's SDK and Java; the NDK is installed by the export when it is missing.
        Target.Android => Android.Find().HasStudio,
        _ => false,
    };

    /// <summary>Why <see cref="CanBuild"/> is false for the target here, for the export's note.</summary>
    public static string WhyNot(Target target) => target switch
    {
        Target.Linux => "a Linux NativeAOT library is linked with Zig, which is not installed (the project selector installs it)",
        Target.Windows => "a Windows NativeAOT library is compiled on Windows or Linux",
        Target.MacOS => ExportUtil.HostMac ? "a macOS NativeAOT library needs Apple's command line tools (run: xcode-select --install)"
            : "a macOS NativeAOT library is compiled on a Mac (Apple's tools only run there)",
        Target.Android => Android.Problem(Android.Find()) ?? Android.StudioHelp,
        _ => "a web build always runs .NET in the browser",
    };

    /// <summary>Whether Apple's command line tools (clang, ld, dsymutil, strip) are installed: /usr/bin/clang is there
    /// either way, as a stand-in that asks to install them.</summary>
    static bool AppleToolsInstalled() => ExportUtil.TryRun("xcode-select", new[] { "-p" }).ExitCode == 0;

    /// <summary>Whether this machine links a Linux library with Zig: always off Linux, and on Linux when Zig is
    /// installed (the library then runs on older distributions than this one; the system's clang links against this
    /// machine's own glibc).</summary>
    static bool UsesZig(Target target) => target == Target.Linux && Zig.Find() != null;

    record AllowEntry(HashSet<string>? Codes, string Origin);

    static List<AllowEntry> Allowlist(string engine)
    {
        var entries = new List<AllowEntry>();
        string path = Path.Combine(engine, "tools", "nativeaot_allowlist.txt");
        if (!File.Exists(path))
            return entries;
        foreach (string line in ExportUtil.ReadText(path).Split('\n'))
        {
            if (line.Trim().Length == 0 || line.TrimStart().StartsWith('#'))
                continue;
            var parts = line.Split((char[]?)null, 3, StringSplitOptions.RemoveEmptyEntries);
            if (parts.Length < 2)
                continue;
            entries.Add(new AllowEntry(parts[0] == "*" ? null : parts[0].Split(',').ToHashSet(), parts[1]));
        }
        return entries;
    }

    /// <summary>The method a warning comes from: 'Ns.Type.Method(Args): text' -> 'Ns.Type.Method'.</summary>
    static string OriginOf(string message)
    {
        var ends = new[] { message.IndexOf('('), message.IndexOf(": ", StringComparison.Ordinal) }.Where(i => i > 0).ToList();
        return ends.Count > 0 ? message[..ends.Min()] : message;
    }

    static bool Allowed(string code, string origin, List<AllowEntry> entries) =>
        entries.Any(entry => (entry.Codes == null || entry.Codes.Contains(code)) &&
            (origin == entry.Origin || origin.StartsWith(entry.Origin + ".", StringComparison.Ordinal) ||
             (entry.Origin.EndsWith('>') && origin.StartsWith(entry.Origin, StringComparison.Ordinal))));

    /// <summary>Namespaces the game's own C# declares (editor scripts left out), and its types outside any namespace.</summary>
    static (HashSet<string> Namespaces, HashSet<string> GlobalTypes) GameNamespaces(string project)
    {
        var namespaces = new HashSet<string>(StringComparer.Ordinal);
        var globalTypes = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (relative, file) in ExportUtil.Files(Path.Combine(project, "src")))
        {
            if (!relative.EndsWith(".cs", StringComparison.Ordinal) || relative.Split('/')[..^1].Contains("Editor"))
                continue;
            string text = ExportUtil.ReadText(file);
            var declared = Regex.Matches(text, @"^\s*namespace\s+([A-Za-z_][\w.]*)", RegexOptions.Multiline).Select(m => m.Groups[1].Value).ToList();
            namespaces.UnionWith(declared);
            if (declared.Count == 0)
                globalTypes.UnionWith(Regex.Matches(text, @"\b(?:class|struct|record|interface)\s+([A-Za-z_]\w*)").Select(m => m.Groups[1].Value));
        }
        return (namespaces, globalTypes);
    }

    static Dictionary<string, List<string>> Classify(List<string> warnings, string project, string engine)
    {
        var (namespaces, globalTypes) = GameNamespaces(project);
        var entries = Allowlist(engine);
        var groups = new Dictionary<string, List<string>>
        {
            ["game"] = new(), ["engine-unreviewed"] = new(), ["engine-allowed"] = new(), ["packages"] = new(), ["dotnet"] = new()
        };
        foreach (string warning in warnings)
        {
            int split = warning.IndexOf(": ", StringComparison.Ordinal);
            string code = split < 0 ? warning : warning[..split];
            string message = split < 0 ? "" : warning[(split + 2)..];
            string origin = OriginOf(message);
            if (namespaces.Any(ns => origin == ns || origin.StartsWith(ns + ".", StringComparison.Ordinal)) || globalTypes.Contains(origin.Split('.')[0]))
                groups["game"].Add(warning);
            else if (origin.StartsWith("Tallow.", StringComparison.Ordinal))
                groups[Allowed(code, origin, entries) ? "engine-allowed" : "engine-unreviewed"].Add(warning);
            else if (Framework.Any(prefix => origin.StartsWith(prefix, StringComparison.Ordinal)))
                groups["dotnet"].Add(warning);
            else
                groups["packages"].Add(warning);
        }
        return groups;
    }

    static string WindowsToolchain()
    {
        string? fromEnvironment = Environment.GetEnvironmentVariable("TALLOW_WIN");
        return !string.IsNullOrEmpty(fromEnvironment) ? fromEnvironment
            : Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".local", "share", "tallow-win");
    }

    /// <summary>Environment and MSBuild properties for linking a win-x64 NativeAOT library on Linux with lld-link and
    /// the xwin Windows SDK + CRT. xwin stores library names in lower case; the ILCompiler names one with capitals.</summary>
    static (Dictionary<string, string> Environment, List<string> Properties) WindowsLinkSetup(string cache)
    {
        string toolchain = WindowsToolchain();
        string xwin = Path.Combine(toolchain, "xwin");
        string linker = Path.Combine(toolchain, "bin", "lld-link");
        if (!File.Exists(linker))
            linker = ExportUtil.Which("lld-link") ?? "";
        if (!Directory.Exists(Path.Combine(xwin, "sdk", "lib", "um", "x86_64")) || !File.Exists(linker))
            throw new ExportException($"A Windows NativeAOT build on Linux needs lld-link and the Windows SDK in {toolchain} (xwin). " +
                "Run tools/windows/setup.sh once, or set TALLOW_WIN to where they are; or export with the JIT runtime.");
        string aliases = Path.Combine(cache, "winlibs");
        Directory.CreateDirectory(aliases);
        foreach (string name in new[] { "Synchronization.lib" })
        {
            string target = Path.Combine(xwin, "sdk", "lib", "um", "x86_64", name.ToLowerInvariant());
            string alias = Path.Combine(aliases, name);
            if (File.Exists(target) && !File.Exists(alias))
                File.CreateSymbolicLink(alias, target);
        }
        string[] folders = { aliases, Path.Combine(xwin, "crt", "lib", "x86_64"), Path.Combine(xwin, "sdk", "lib", "um", "x86_64"),
            Path.Combine(xwin, "sdk", "lib", "ucrt", "x86_64") };
        return (new Dictionary<string, string> { ["LIB"] = string.Join(';', folders) },
            new List<string> { "-p:DisableUnsupportedError=true", "-p:IlcUseEnvironmentalTools=true", "-p:EnableSourceLink=false", "-p:CppLinker=" + linker });
    }

    /// <summary>The Windows lld-link Beef's toolchain carries, run under Wine, for a Linux lld that crashes building
    /// the Windows PDB (lld 22.1.8 segfaults in its GSI hash writer for a large symbol set). Null when unavailable.</summary>
    static (string Wrapper, Dictionary<string, string> Environment)? WineLinkSetup(string cache, string work)
    {
        string toolchain = WindowsToolchain();
        string linker = Path.Combine(toolchain, "beef", "bin", "llvm", "bin", "lld-link.exe");
        if (!File.Exists(linker) || ExportUtil.Which("wine") == null)
            return null;
        string wrapper = Path.Combine(work, "lld-link-wine");
        File.WriteAllText(wrapper,
            "#!/bin/sh\n" +
            // lld-link opens the response file before handling the paths inside it.
            "for argument do\n" +
            "    shift\n" +
            "    case \"$argument\" in @/*) argument=\"@Z:${argument#@}\" ;; esac\n" +
            "    set -- \"$@\" \"$argument\"\n" +
            "done\n" +
            $"exec wine '{linker.Replace("'", "'\\''")}' \"$@\"\n");
        ExportUtil.MakeExecutable(wrapper);
        string xwin = Path.Combine(toolchain, "xwin");
        string[] folders = { Path.Combine(cache, "winlibs"), Path.Combine(xwin, "crt", "lib", "x86_64"), Path.Combine(xwin, "sdk", "lib", "um", "x86_64"),
            Path.Combine(xwin, "sdk", "lib", "ucrt", "x86_64") };
        return (wrapper, new Dictionary<string, string>
        {
            ["LIB"] = string.Join(';', folders.Select(folder => "Z:" + folder.Replace('/', '\\'))),
            ["WINEPREFIX"] = Path.Combine(toolchain, "wine"),
            ["WINEDEBUG"] = "-all",
        });
    }

    /// <summary>The game's own compiled assemblies (Tallow.Game, its .tasmdef assemblies and NuGet packages).</summary>
    public static List<string> GameAssemblies(string project, string config)
    {
        string built = Path.Combine(project, "build", "csharp", config);
        var result = new List<string>();
        if (Directory.Exists(built))
            foreach (string folder in Directory.EnumerateDirectories(built).Order(StringComparer.Ordinal))
                foreach (string dll in Directory.EnumerateFiles(folder, "*.dll").Order(StringComparer.Ordinal))
                {
                    string stem = Path.GetFileNameWithoutExtension(dll);
                    if (stem is not ("Tallow.API" or "Tallow.ManagedRuntime") && !result.Any(path => Path.GetFileName(path) == Path.GetFileName(dll)))
                        result.Add(dll);
                }
        if (!result.Any(path => Path.GetFileName(path) == "Tallow.Game.dll"))
            throw new ExportException($"The game's C# is not built ({built}/Tallow.Game/Tallow.Game.dll is missing).");
        return result;
    }

    static string X(string text) => SecurityElement.Escape(text);

    static string ProjectFile(string engine, List<string> assemblies)
    {
        var references = new StringBuilder();
        foreach (string dll in assemblies)
        {
            string stem = Path.GetFileNameWithoutExtension(dll);
            references.Append($"    <Reference Include=\"{X(stem)}\"><HintPath>{X(dll)}</HintPath></Reference>\n");
            references.Append($"    <TrimmerRootAssembly Include=\"{X(stem)}\" />\n");
        }
        string runtime = Path.Combine(engine, "Managed", "Tallow.ManagedRuntime", "Tallow.ManagedRuntime.csproj");
        return $"""
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>net{DotNetRuntime.Major}.0</TargetFramework>
                <OutputType>Library</OutputType>
                <AssemblyName>TallowGame</AssemblyName>
                <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
                <Nullable>enable</Nullable>
                <PublishAot>true</PublishAot>
                <NativeLib>Shared</NativeLib>
                <!-- Native symbols are made (and kept out of the package by the export). -->
                <NativeDebugSymbols>true</NativeDebugSymbols>
                <StripSymbols>true</StripSymbols>
                <!-- Exception reports keep their method names and source lines (as on .NET). -->
                <StackTraceSupport>true</StackTraceSupport>
                <!-- Every warning of the trim/AOT analysis is shown, one by one, so the build's report can list them. -->
                <TrimmerSingleWarn>false</TrimmerSingleWarn>
                <SuppressTrimAnalysisWarnings>false</SuppressTrimAnalysisWarnings>
                <!-- No IlcInstructionSet: the library runs on every x64 CPU the JIT export runs on, with the same float maths. -->
              </PropertyGroup>
              <ItemGroup>
                <ProjectReference Include="{X(runtime)}" />
                <!-- Kept whole: the runtime reads the game's fields, [Rpc] methods and callbacks by reflection. -->
                <TrimmerRootAssembly Include="Tallow.ManagedRuntime" />
                <TrimmerRootAssembly Include="Tallow.API" />
            {references}  </ItemGroup>
            </Project>

            """;
    }

    /// <summary>Compiles the NativeAOT library into staging/Managed/Native and its native symbols into
    /// <paramref name="symbols"/>. With <paramref name="warningsMode"/> "error", a warning in the game's own code, or
    /// an engine warning not in tools/nativeaot_allowlist.txt, fails the export (after the report is written).</summary>
    public static void Build(string engine, string project, string config, string staging, Target target, string player, string symbols, string warningsMode,
        AndroidTools? android = null, string? androidAbi = null)
    {
        if (target != Target.Android && !CanBuild(target))
            throw new ExportException($"No NativeAOT build here: {WhyNot(target)}.");
        bool windows = target == Target.Windows, macos = target == Target.MacOS;
        // A macOS library is for the chip the player is built for (an Intel player runs on Apple silicon too, translated).
        string rid = target == Target.Android ? Android.Rid(androidAbi!) : windows ? "win-x64" : macos ? "osx-" + (Symbols.MachOArch(player) ?? "x64") : "linux-x64";
        var assemblies = GameAssemblies(project, config);
        string cache = Path.Combine(ExportUtil.CacheFolder(), "nativeaot");
        var environment = new Dictionary<string, string> { ["DOTNET_NOLOGO"] = "1" };
        var properties = new List<string>();
        bool cross = windows && !ExportUtil.HostWindows;
        string work = Directory.CreateTempSubdirectory("tallow-native-").FullName;
        if (target == Target.Android)
            properties = Android.LinkProperties(android!, androidAbi!);
        else if (cross)
        {
            var (extra, crossProperties) = WindowsLinkSetup(cache);
            foreach (var (key, value) in extra)
                environment[key] = value;
            properties = crossProperties;
        }
        else if (UsesZig(target))
        {
            Console.WriteLine($"Linking with Zig {Zig.Version} (for glibc {Zig.Glibc} and later).");
            var (extra, zigProperties) = Zig.LinkSetup(Zig.Find()!, work);
            foreach (var (key, value) in extra)
                environment[key] = value;
            properties = zigProperties;
        }
        try
        {
            File.WriteAllText(Path.Combine(work, "TallowGame.csproj"), ProjectFile(engine, assemblies));
            File.WriteAllText(Path.Combine(work, "Exports.cs"), Exports);
            string published = Path.Combine(work, "out");
            Console.WriteLine($"Compiling the game to native code ({rid}, NativeAOT)...");
            var command = new List<string> { "publish", Path.Combine(work, "TallowGame.csproj"), "-c", config, "-r", rid, "-o", published,
                "--artifacts-path", Path.Combine(work, "artifacts"), "--nologo", "-v", "minimal" };
            var result = ExportUtil.Run("dotnet", command.Concat(properties), true, null, environment);
            string firstOutput = "";
            if (result.ExitCode != 0 && cross && (result.All.Contains("exited with code 139") || result.All.Contains("Segmentation fault")))
            {
                // A crash in the linker itself, not the game: the Windows lld Beef's toolchain carries links the same input.
                var fallback = WineLinkSetup(cache, work);
                if (fallback != null)
                {
                    var (wrapper, extra) = fallback.Value;
                    Console.WriteLine("note: lld-link crashed; linking again with the toolchain's lld-link under Wine.");
                    firstOutput = result.All;
                    var retryEnvironment = new Dictionary<string, string>(environment);
                    foreach (var (key, value) in extra)
                        retryEnvironment[key] = value;
                    var retry = properties.Where(property => !property.StartsWith("-p:CppLinker=", StringComparison.Ordinal)).Append("-p:CppLinker=" + wrapper);
                    result = ExportUtil.Run("dotnet", command.Concat(retry), true, null, retryEnvironment);
                }
            }
            // The retry reuses ILCompiler's cache, so its output has no analysis warnings: read both runs'.
            var warnings = new List<string>();
            foreach (string line in (firstOutput + "\n" + result.All).Split('\n'))
            {
                Match match = Analysis.Match(line.TrimEnd('\r'));
                if (match.Success)
                {
                    string entry = $"{match.Groups[1].Value}: {match.Groups[2].Value.Trim()}";
                    if (!warnings.Contains(entry))
                        warnings.Add(entry);
                }
            }
            string library = Path.Combine(published, LibraryName(target));
            if (result.ExitCode != 0 || !File.Exists(library))
            {
                var lines = result.All.Split('\n');
                var problems = lines.Where(line => line.Contains(" error ") || line.Contains("error:")).ToList();
                string hint = "";
                if (result.All.Contains("linker", StringComparison.OrdinalIgnoreCase) && result.All.Contains("not found", StringComparison.OrdinalIgnoreCase))
                    hint = "\n\nNativeAOT links with the system's C/C++ tools: on Windows, Visual Studio (or its Build Tools) with " +
                        "\"Desktop development with C++\"; for Linux, Zig (the project selector installs it) or, on Linux, clang (or gcc); " +
                        "on a Mac, Apple's command line tools (xcode-select --install). " +
                        "Install them, or export with the JIT runtime (Build window: JIT; --csharp-runtime jit).";
                var shown = problems.Count > 0 ? problems.TakeLast(30) : lines.TakeLast(40);
                throw new ExportException("The NativeAOT build failed:\n" + string.Join('\n', shown) + hint);
            }
            string native = Path.Combine(staging, "Managed", "Native");
            Directory.CreateDirectory(native);
            string shipped = Path.Combine(native, Path.GetFileName(library));
            File.Copy(library, shipped, true);
            if (!windows)
                ExportUtil.MakeExecutable(shipped);
            // Which code this is (network sessions compare it; see CSharpNetReload).
            string built = Path.Combine(project, "build", "csharp", config);
            string codeId = Path.Combine(built, "Tallow.Game", "Tallow.Game.codeid");
            if (File.Exists(codeId))
                File.Copy(codeId, Path.Combine(native, "Tallow.Game.codeid"), true);
            string notices = Path.Combine(built, "THIRD-PARTY-NOTICES.txt");
            if (File.Exists(notices))
                File.Copy(notices, Path.Combine(staging, "THIRD-PARTY-NOTICES.txt"), true);
            // Private: matching native symbols for crash reports, never shipped.
            if (Directory.Exists(symbols))
                Directory.Delete(symbols, true);
            Directory.CreateDirectory(symbols);
            // Windows: a .pdb; Linux: a .dbg; macOS: a .dSYM folder (dsymutil's).
            string wanted = windows ? Path.GetFileNameWithoutExtension(library) + ".pdb" : Path.GetFileName(library) + (macos ? ".dSYM" : ".dbg");
            string artifacts = Path.Combine(work, "artifacts");
            var candidates = new[] { Path.Combine(published, wanted) }.Concat(!Directory.Exists(artifacts) ? Enumerable.Empty<string>()
                : (macos ? Directory.EnumerateDirectories(artifacts, wanted, SearchOption.AllDirectories)
                    : Directory.EnumerateFiles(artifacts, wanted, SearchOption.AllDirectories))
                    .Where(path => path.Replace('\\', '/').Contains("/native/")));
            string? found = candidates.FirstOrDefault(path => macos ? Directory.Exists(path) : File.Exists(path));
            if (found != null && macos)
                ExportUtil.CopyTree(found, Path.Combine(symbols, wanted));
            else if (found != null)
                File.Copy(found, Path.Combine(symbols, wanted), true);
            else
                Console.WriteLine($"warning: the native symbols ({wanted}) were not made; crash reports of this build cannot be read.");
            var groups = Classify(warnings, project, engine);
            var titles = new (string Key, string Title)[]
            {
                ("game", "in the game's own code (fail the export)"),
                ("engine-unreviewed", "in the engine, not in tools/nativeaot_allowlist.txt (fail the export)"),
                ("engine-allowed", "in the engine, reviewed (tools/nativeaot_allowlist.txt)"),
                ("packages", "in third-party packages (reported only)"),
                ("dotnet", "in .NET itself (reported only)"),
            };
            var report = new List<string>
            {
                $"NativeAOT build of {Path.GetFileName(project)} ({rid}, {config})",
                $"library: {Path.GetFileName(library)} ({new FileInfo(library).Length / 1024} KB)",
                $"trim/AOT analysis warnings: {warnings.Count}",
            };
            foreach (var (key, title) in titles)
            {
                report.Add("");
                report.Add($"{groups[key].Count} {title}");
                report.AddRange(groups[key]);
            }
            string reportPath = Path.Combine(symbols, "nativeaot-report.txt");
            File.WriteAllText(reportPath, string.Join('\n', report) + "\n", new UTF8Encoding(false));
            Console.WriteLine($"NativeAOT: {Path.GetFileName(library)} {new FileInfo(shipped).Length / (1024 * 1024)} MB; symbols in {symbols}; " +
                $"{warnings.Count} trim/AOT warning(s): {groups["game"].Count} in the game, " +
                $"{groups["engine-allowed"].Count + groups["engine-unreviewed"].Count} in the engine ({groups["engine-unreviewed"].Count} not reviewed), " +
                $"{groups["packages"].Count} in packages, {groups["dotnet"].Count} in .NET (listed in {reportPath})");
            if (warningsMode == "error" && groups["game"].Count + groups["engine-unreviewed"].Count > 0)
            {
                var lines = new List<string> { "The NativeAOT export stopped on trim/AOT warnings:" };
                if (groups["game"].Count > 0)
                {
                    lines.Add("");
                    lines.AddRange(groups["game"]);
                    lines.Add("");
                    lines.Add(GameHelp);
                }
                if (groups["engine-unreviewed"].Count > 0)
                {
                    lines.Add("");
                    lines.Add("Engine warnings nobody has reviewed (add each to tools/nativeaot_allowlist.txt with its reason once it is known to be safe, or change the engine code):");
                    lines.AddRange(groups["engine-unreviewed"]);
                }
                lines.Add("");
                lines.Add("--aot-warnings report exports anyway.");
                throw new ExportException(string.Join('\n', lines));
            }
        }
        finally
        {
            Directory.Delete(work, true);
        }
    }
}
